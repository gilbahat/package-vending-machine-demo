#!/usr/bin/env bash
#
# build-unikernel.sh -- cross-build vend.hvt. Runs INSIDE the image built from
# docker/Dockerfile.build; see `make unikernel`.
#
# The verified library is vendored into the unikernel's dune project rather
# than installed as an opam package. Mirage builds the unikernel in a separate
# dune context that uses the `solo5` findlib toolchain, so a host-installed
# library would be the wrong architecture. Vendoring lets dune build it in the
# solo5 context along with everything else, and keeps generated/ as the single
# source of truth in the repository.
#
# Copyright (c) 2026. SPDX-License-Identifier: ISC

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
UK="$ROOT/unikernel"

echo "==> vendoring the verified library"
rm -rf "$UK/vendor"
mkdir -p "$UK/vendor"
cp "$ROOT"/generated/*.c "$ROOT"/generated/*.h "$UK/vendor/"
cp "$ROOT"/verified/vend_shim.c "$ROOT"/verified/vend_shim.h \
   "$ROOT"/verified/vend_stubs.c \
   "$ROOT"/verified/vend_verified.ml "$ROOT"/verified/vend_verified.mli \
   "$UK/vendor/"

# VendManifestWrapper.c is deliberately not compiled: vend_shim.c supersedes it
# because the generated wrapper does not require the parse to consume the whole
# buffer. See verified/vend_shim.h.
rm -f "$UK/vendor/VendManifestWrapper.c" "$UK/vendor/VendManifestWrapper.h"

cat > "$UK/vendor/dune" <<'EOF'
; Generated by scripts/build-unikernel.sh -- do not edit.
; Sources are copied from ../../generated and ../../verified.
(library
 (name vend_verified)
 (foreign_stubs
  (language c)
  (names Vend_Url VendManifest vend_shim vend_stubs)
  ; EverParseEndianness.h sniffs the platform via __linux__/__APPLE__/_WIN32
  ; and #errors out on anything else -- which includes a freestanding Solo5
  ; target. ocaml-solo5's libc does provide a conforming <endian.h>, so we
  ; take the header's own escape hatch and point it at that.
  (flags :standard -I. -Wno-parentheses -D__USE_SYSTEM_ENDIAN_H__)))
EOF

echo "==> staging assets"
mkdir -p "$UK/assets"
if [ ! -f "$ROOT/manifest.bin" ]; then
  echo "manifest.bin missing -- run 'make manifest' first" >&2
  exit 1
fi
cp "$ROOT/manifest.bin" "$UK/assets/manifest.bin"
cp "$ROOT/keys/manifest.pub" "$UK/assets/manifest.pub"

echo "==> mirage configure -t hvt"
cd "$UK"
mirage configure -t hvt

# The standard mirage flow: lock the dependency set, vendor every dependency
# as SOURCE into duniverse/, then build everything -- including the C stubs of
# mirage-solo5 -- inside the solo5 dune context. Host-installed archives
# cannot be linked into a freestanding binary.
echo "==> make lock (resolving the dependency set)"
make lock

echo "==> make pull (vendoring sources into duniverse/)"
make pull

echo "==> dune build"
dune build

mkdir -p "$ROOT/build"
cp "$UK/dist/vend.hvt" "$ROOT/build/vend.hvt"

echo
echo "==> built build/vend.hvt"
ls -la "$ROOT/build/vend.hvt"
size "$ROOT/build/vend.hvt" 2>/dev/null || true
echo
echo "Solo5 manifest (the devices this unikernel may use at all):"
solo5-elftool query-manifest "$ROOT/build/vend.hvt" 2>/dev/null || true
