#!/usr/bin/env bash
#
# closure.sh -- derive a transitive dependency closure for the allowlist.
#
#   usage: scripts/closure.sh requirements.txt > spec/packages.txt
#
# An allowlist that contains only the packages you asked for will fail on
# first use: `pip install requests` also needs urllib3, certifi,
# charset-normalizer and idna. This resolves the closure with pip itself and
# emits it in the 'ecosystem:name' format build_manifest.py expects.
#
# Note what this does NOT do: pin versions. The vending machine deliberately
# serves whatever versions the upstream index currently offers, so that an
# agent can fetch a closure it did not know about in advance. Safety of the
# resulting upstream URL is the F* validator's job.
#
# Copyright (c) 2026. SPDX-License-Identifier: ISC

set -euo pipefail

REQ="${1:-}"
if [ -z "$REQ" ] || [ ! -f "$REQ" ]; then
  echo "usage: $0 <requirements.txt>" >&2
  exit 1
fi

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

echo "# Generated by scripts/closure.sh from $REQ"
echo "# Transitive closure; versions intentionally unpinned."
echo

# `pip download` resolves the full graph without installing anything. We only
# want the names, so read them back off the downloaded filenames.
python3 -m pip download \
  --dest "$TMP" \
  --no-binary :all: \
  --no-build-isolation \
  -r "$REQ" >/dev/null 2>&1 || {
    echo "pip download failed; falling back to a binary resolve" >&2
    python3 -m pip download --dest "$TMP" -r "$REQ" >/dev/null
  }

for f in "$TMP"/*; do
  base="$(basename "$f")"
  # strip extension, then take everything before the first -<digit>
  name="$(printf '%s' "$base" \
    | sed -E 's/\.(tar\.gz|tar\.bz2|tar\.xz|zip|whl|egg)$//' \
    | sed -E 's/-[0-9].*$//')"
  # PyPI normalises names to lowercase with '-' separators
  printf 'pypi:%s\n' "$(printf '%s' "$name" | tr '[:upper:]_' '[:lower:]-')"
done | sort -u
